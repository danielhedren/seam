#!/bin/sh
# Vendors the tree-sitter grammars of SPEC §8.4 into Vendor/Grammars, each as a C target's
# sources, its highlight queries and its licence. Rerun after changing a ref below.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/Vendor/Grammars"
queries="$root/Sources/Highlighting/Queries"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
rm -rf "$out" "$queries"
mkdir -p "$out" "$queries"
echo "# Vendored tree-sitter grammars (generated by Scripts/vendor-grammars.sh)" > "$out/VERSIONS.md"

# name  repository  ref  grammar-directory  symbol  extra-files
grammars='
csharp      tree-sitter/tree-sitter-c-sharp         v0.23.5                     .                      tree_sitter_c_sharp     -
typescript  tree-sitter/tree-sitter-typescript      v0.23.2                     typescript             tree_sitter_typescript  common
tsx         tree-sitter/tree-sitter-typescript      v0.23.2                     tsx                    tree_sitter_tsx         common
javascript  tree-sitter/tree-sitter-javascript      v0.25.0                     .                      tree_sitter_javascript  -
json        tree-sitter/tree-sitter-json            v0.24.8                     .                      tree_sitter_json        -
yaml        tree-sitter-grammars/tree-sitter-yaml   v0.7.2                      .                      tree_sitter_yaml        -
markdown    tree-sitter-grammars/tree-sitter-markdown v0.5.3                    tree-sitter-markdown   tree_sitter_markdown    -
xml         tree-sitter-grammars/tree-sitter-xml    v0.7.0                      xml                    tree_sitter_xml         common
rust        tree-sitter/tree-sitter-rust            v0.24.2                     .                      tree_sitter_rust        -
toml        tree-sitter-grammars/tree-sitter-toml   v0.7.0                      .                      tree_sitter_toml        -
dockerfile  camdencheek/tree-sitter-dockerfile      v0.2.0                      .                      tree_sitter_dockerfile  -
php         tree-sitter/tree-sitter-php             v0.24.2                     php                    tree_sitter_php         common
'

echo "$grammars" | while read -r name repo ref dir symbol extra; do
    [ -n "$name" ] || continue
    clone="$work/$(basename "$repo")-$ref"
    if [ ! -d "$clone" ]; then
        git init -q "$clone"
        git -C "$clone" fetch -q --depth 1 "https://github.com/$repo" "$ref"
        git -C "$clone" checkout -q FETCH_HEAD
    fi
    target="$out/$name"
    # Keep the grammar's own layout: scanners include "../../common/scanner.h".
    mkdir -p "$target/grammar/$dir/src" "$target/include"
    # parser.c and the scanner; YAML's scanner also includes one schema.*.c by macro.
    for file in "$clone/$dir/src/parser.c" "$clone/$dir/src/scanner.c" "$clone/$dir/src/"schema.*.c; do
        [ -f "$file" ] && cp "$file" "$target/grammar/$dir/src/"
    done
    cp -R "$clone/$dir/src/tree_sitter" "$target/grammar/$dir/src/"
    [ "$extra" = "-" ] || cp -R "$clone/$extra" "$target/grammar/"
    cp "$clone/LICENSE"* "$target/" 2>/dev/null || true
    printf '// Declared as void: the real return type is the runtime'"'"'s TSLanguage, which this\n// module does not import. Swift passes the pointer on as an OpaquePointer.\nconst void *%s(void);\n' \
        "$symbol" > "$target/include/$name.h"
    commit="$(git -C "$clone" rev-parse HEAD)"
    echo "- $name: $repo @ $ref ($commit)" >> "$out/VERSIONS.md"
done

# Highlight queries, combined where a grammar extends another (tree-sitter.json "highlights").
# The clone the loop above made for a grammar, so the refs live only in the table.
clone() { echo "$grammars" | awk -v name="$1" '$1 == name { sub(".*/", "", $2); print $2 "-" $3 }'; }
copy_query() { cat "$@" > "$queries/$name.scm"; }
for name in csharp javascript json yaml rust toml dockerfile php; do
    copy_query "$work/$(clone "$name")/queries/highlights.scm"
done
name=markdown; copy_query "$work/$(clone markdown)/tree-sitter-markdown/queries/highlights.scm"
name=xml; copy_query "$work/$(clone xml)/queries/xml/highlights.scm"
for name in typescript tsx; do
    copy_query "$work/$(clone typescript)/queries/highlights.scm" \
        "$work/$(clone javascript)/queries/highlights.scm"
done
echo "vendored $(ls "$out" | grep -vc VERSIONS) grammars into $out"
